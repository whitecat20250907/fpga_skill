"""Deterministic 16x16 2-bit AA glyphs and sparse Chinese dashboard labels.

System font is read locally, never copied. Assets are 256*16*32 bits, no RGB
frame. Geometry and observed results are not rendered by this generator.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont

HERE=Path(__file__).resolve().parent
FONT=Path('C:/Windows/Fonts/msyh.ttc')
LABELS={
 49:'已锁定 · 等待手势',50:'眼控正在选目标',51:'眼控未启用',
 52:'菜单',53:'标定中',54:'评测中',55:'标定完成',56:'评测完成',57:'平均',58:'命中',59:'停留',60:'有效',61:'目标',62:'项',63:'无数据',
 0:'',1:'等待注册',2:'实时特征',3:'合成测试',4:'仅显示',5:'轨迹模式',6:'游戏模式',
 7:'等待输入',8:'握拳',9:'指向',10:'张掌',11:'胜利',12:'拇指上',13:'拇指下',
 14:'放松',15:'未知手势',16:'待释放',17:'已就绪',18:'记录中',19:'结果',20:'已拒绝',
 21:'等待',22:'相对示意',23:'未标定示意',24:'真实投影',25:'未分配',26:'跟踪中',
 27:'未标定',28:'已标定',29:'真实轨迹',30:'无结果',31:'已识别',32:'',33:'已失效',
 34:'左手',35:'右手',36:'手部待关联',37:'按物理键翻页',38:'五动作控制',39:'握拳准备 · 指向记录',
 40:'合成测试 · 非真人',41:'源已失效',42:'等待新来源',43:'仅显示特征',44:'人物页不是身份',
 45:'待识别',46:'单人页面',47:'多模态交互',48:'游戏输入待验证',
}
STATIC=[(0,0,'交互孪生'),(4,2,'FPGA / RK3576'),(2,42,'人物 1'),(2,51,'人物 2'),
 (5,15,'同源实时特征'),(7,3,'手部实时孪生'),(7,39,'头部'),(7,47,'眼屏位置'),
 (28,4,'左手'),(28,20,'右手'),(28,39,'真实轨迹'),(30,2,'轨迹识别'),
 (30,43,'仅显示真实结果'),(36,2,'MENU 菜单 · 手势操作'),(36,39,'眼控接管 · 握拳锁定')]
CHIPS=['0','L','L反','L上','L反上','M','W','Z']


def main():
    texts=[t for _,_,t in STATIC]+list(LABELS.values())+CHIPS+['桌面眼控游戏医学演示轨迹书写标定当前使用者单人双人第一人登记标定第二人登记标定待机采样']
    extra=sorted(set(''.join(texts))-set(map(chr,range(128))))
    free=list(range(128,256))+list(range(1,32))
    assert len(extra)<=len(free)
    mapping={chr(n):n for n in range(128)};mapping.update(zip(extra,free))
    bycode={v:k for k,v in mapping.items()}
    font=ImageFont.truetype(str(FONT),60,index=0)
    rows=[];levels=set()
    for code in range(256):
        letter=bycode.get(code,' ')
        im=Image.new('L',(64,64));draw=ImageDraw.Draw(im)
        if code>=32 and letter!=' ' or code in set(mapping[c] for c in extra):
            box=draw.textbbox((0,0),letter,font=font)
            draw.text(((64-(box[2]-box[0]))//2-box[0],(64-(box[3]-box[1]))//2-box[1]),letter,font=font,fill=255)
        im=im.resize((16,16),Image.Resampling.LANCZOS)
        for y in range(16):
            row=0
            for x in range(16):
                alpha=min(3,(im.getpixel((x,y))+42)//85);row=(row<<2)|alpha;levels.add(alpha)
            rows.append(row)
    assert len(rows)==4096 and levels=={0,1,2,3}
    (HERE/'twin_font.mem').write_text(''.join(f'{v:08x}\n' for v in rows),encoding='ascii')
    # Vendor PH1_LOGIC_ERAM INIT format matches the existing DSI/glyph ROM.
    mif='DEPTH = 4096;\nWIDTH = 32;\nADDRESS_RADIX = HEX;\nDATA_RADIX = HEX;\nCONTENT BEGIN\n'
    mif+=''.join(f'{i:03X} : {v:08X};\n' for i,v in enumerate(rows))+'END;\n'
    (HERE/'twin_glyph_font_aa.mif').write_text(mif,encoding='ascii')
    grid=[32]*(64*38)
    for row,col,text in STATIC:
        for pos,letter in enumerate(text):
            assert col+pos<64
            grid[row*64+col+pos]=mapping[letter]
    for index,label in enumerate(CHIPS):
        x=32+index*120+56-len(label)*8;col=round(x/16)
        for pos,letter in enumerate(label):grid[32*64+col+pos]=mapping[letter]
    (HERE/'twin_text.mem').write_text(''.join(f'{v:02x}\n' for v in grid),encoding='ascii')
    definitions=['// Generated by generate_assets.py; label IDs documented in assets_manifest.json.',
     'function [7:0] label_char;',' input [5:0] label_id;input [5:0] position;',
     ' begin','  case({label_id,position})']
    for label,text in LABELS.items():
        for pos,letter in enumerate(text):definitions.append(f"   12'd{label*64+pos}:label_char=8'd{mapping[letter]};")
    definitions+=['   default:label_char=8\'d32;','  endcase',' end','endfunction']
    (HERE/'dashboard_labels.vh').write_text('\n'.join(definitions)+'\n',encoding='ascii')
    manifest=dict(schema='TWIN_DASHBOARD_AA_ASSETS_V1',glyphs=256,width=16,height=16,bits_per_pixel=2,
      font_bits=131072,font_eram_upper_budget=8,no_rgb_framebuffer=True,alpha_levels=sorted(levels),
      font_source=dict(path=str(FONT),sha256=hashlib.sha256(FONT.read_bytes()).hexdigest(),index=0),
      source_font_file_copied=False,unicode_glyphs=len(extra),labels=LABELS,character_codes=mapping,
      chip_labels=CHIPS,static_labels=STATIC)
    (HERE/'assets_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    print('ASSETS',len(extra),'Chinese/punctuation glyphs;',len(rows)*32,'font bits')


if __name__=='__main__':main()
